import { useState } from "react";
import type { SubmitEvent } from "react";
import { useUser } from "../contexts/UserContext";
import { API_URL, authHeaders, getErrorMessage } from "../utils/api";
import type { TripRecommendation } from "../types/Ai";

const MAX_DESTINATION = 80;
const EXAMPLES = ["Lisbon", "Kyoto", "Cape Town", "Iceland"];

export default function AiRecommendation() {
  const { token, logout } = useUser();

  const [destination, setDestination] = useState<string>("");
  const [recommendation, setRecommendation] = useState<TripRecommendation | null>(null);
  const [loading, setLoading] = useState<boolean>(false);
  const [error, setError] = useState<string>("");

  async function getRecommendation(value: string) {
    const place = value.trim();

    if (!place) {
      setError("Please enter a destination");
      return;
    }
    if (place.length > MAX_DESTINATION) {
      setError(`The destination can be up to ${MAX_DESTINATION} characters`);
      return;
    }

    setLoading(true);
    setError("");
    setRecommendation(null);
    try {
      const response = await fetch(`${API_URL}/ai/recommendation`, {
        method: "POST",
        headers: { "Content-Type": "application/json", ...authHeaders(token) },
        body: JSON.stringify({ destination: place })
      });

      if (response.status === 401) {
        logout();
        return;
      }
      if (!response.ok) {
        // 422 = not a real place · 503 = the AI is busy — the server explains which
        setError(await getErrorMessage(response, "Failed to get a recommendation"));
        return;
      }

      const data: TripRecommendation = await response.json();
      setRecommendation(data);
    } catch {
      setError("Cannot reach the server. Please try again later.");
    } finally {
      setLoading(false);
    }
  }

  function handleSubmit(e: SubmitEvent<HTMLFormElement>) {
    e.preventDefault();
    getRecommendation(destination);
  }

  function tryExample(example: string) {
    setDestination(example);
    getRecommendation(example);
  }

  return (
    <div className="page">
      <h1>AI Trip Recommendation</h1>
      <p className="summary">Enter a destination and get a personal trip plan, written by AI (Google Gemini).</p>

      <form className="ai-form" onSubmit={handleSubmit} noValidate>
        <input
          className="ai-input"
          placeholder="Where do you want to go? e.g. Lisbon"
          value={destination}
          maxLength={MAX_DESTINATION}
          onChange={(e) => setDestination(e.target.value)}
          aria-label="Destination"
        />
        <button className="btn btn-primary" type="submit" disabled={loading}>
          {loading ? "Planning..." : "✨ Get recommendation"}
        </button>
      </form>

      <div className="examples">
        <span>Try:</span>
        {EXAMPLES.map((example) => (
          <button key={example} className="example-btn" onClick={() => tryExample(example)} disabled={loading}>
            {example}
          </button>
        ))}
      </div>

      {error && <p className="status error">{error}</p>}
      {loading && <p className="status">✨ The AI is planning your trip... (a few seconds)</p>}

      {recommendation && (
        <div className="ai-result">
          <h2>{recommendation.destination}</h2>
          <p className="ai-summary">{recommendation.summary}</p>

          <div className="ai-best-time">
            <strong>📅 Best time to visit:</strong> {recommendation.bestTimeToVisit}
          </div>

          <div className="ai-sections">
            <section>
              <h3>📍 Top attractions</h3>
              <ul>{recommendation.topAttractions.map((item) => <li key={item}>{item}</li>)}</ul>
            </section>

            <section>
              <h3>🍽️ Local food</h3>
              <ul>{recommendation.localFood.map((item) => <li key={item}>{item}</li>)}</ul>
            </section>

            <section>
              <h3>💡 Tips</h3>
              <ul>{recommendation.tips.map((item) => <li key={item}>{item}</li>)}</ul>
            </section>
          </div>

          <h3>🗓️ Suggested itinerary</h3>
          <ol className="ai-itinerary">
            {recommendation.itinerary.map((day) => (
              <li key={day.day}>
                <strong>Day {day.day}:</strong> {day.plan}
              </li>
            ))}
          </ol>

          <p className="ai-note">Generated by AI — check opening hours and prices before you travel.</p>
        </div>
      )}
    </div>
  );
}
